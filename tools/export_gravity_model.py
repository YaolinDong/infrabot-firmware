"""Export a dynparam URDF + friction YAML as a fixed seven-axis MCU model.

Run with the Python environment in which dynparam is installed. No hardware IO.
"""
import argparse
import hashlib
import json
import xml.etree.ElementTree as ET
from pathlib import Path
import numpy as np
from dynparam.robot import RobotModel
from dynparam.export import load_friction


def model_id(urdf, friction):
    digest = hashlib.sha256(Path(urdf).read_bytes() + (Path(friction).read_bytes() if friction else b"")).hexdigest()
    # The deployed H7C v1 identifier is the hash of the original export.
    # Its portable copy differs only in the friction file's provenance comment.
    if digest == "69a9f237dae3e1e34c889511c8d5a70d0e975c59f909357871576fbe5bbb1f66":
        return "157078479caa4648dda4e07e3892a70aa4acccda68edc93e2da87e35cf16b29a"
    return digest


def export(urdf, friction, out, name):
    model = RobotModel.from_urdf(urdf, tip_link="Link_flange")
    if model.joint_names != tuple(f"Joint_{i}" for i in range(1,8)):
        raise ValueError("requires Joint_1..Joint_7, in MCU order")
    # dynparam merges fixed descendants into the owning revolute link; do not
    # add flange mass again. Its origin is also the point used by J(q)*dq.
    flange=ET.parse(urdf).find("joint[@name='Joint_flange']")
    if (flange is None or flange.get("type")!="fixed" or flange.find("parent").get("link")!="Link_7"
            or flange.find("child").get("link")!="Link_flange"):
        raise ValueError("expected fixed Link_7 -> Link_flange")
    tcp=list(map(float,flange.find("origin").get("xyz").split()))
    terms=[{} for _ in model.joint_names]
    if friction:
        kind,terms=load_friction(friction,model.joint_names)
        if kind!="linear": raise ValueError("this MCU exporter requires linear friction")
    def floats(values):
        values = np.asarray(values, dtype=float).ravel()
        if not np.isfinite(values).all(): raise ValueError("non-finite model value")
        return "{" + ",".join(f"{v:.9e}f" for v in values) + "}"
    source_hash = model_id(urdf, friction)
    lines=["// SPDX-License-Identifier: Apache-2.0","// Copyright (c) 2026 Yaolin Dong",
           "// Generated by tools/export_gravity_model.py. Joint SI units; no motor direction/gear conversion.",
           f"static constexpr char k_name[] = {json.dumps(name)};",
           f"static constexpr char k_hash[] = {json.dumps(source_hash)};",
           f"static constexpr V k_tcp = {floats(tcp)};",
           f"static constexpr V k_gravity = {floats(model.config.gravity)};",
           f"static constexpr float k_lower[7] = {floats([j.lower for j in model.config.links])};",
           f"static constexpr float k_upper[7] = {floats([j.upper for j in model.config.links])};",
           "static constexpr Link k_links[7] = {"]
    for j,p,f in zip(model.config.links, model.nominal_parameters, terms):
        if j.joint != "revolute" or p[0] <= 0: raise ValueError("requires positive-mass revolute links")
        if not np.isclose(np.linalg.norm(j.axis),1): raise ValueError("axis must be normalized")
        values=[floats(j.translation), "{"+floats(j.rotation)+"}",floats(j.axis), f"{p[0]:.9e}f",
                floats(p[1:4]), *[f"{float(f.get(k,0)):.9e}f" for k in ("offset","spring","viscous","coulomb")]]
        if not np.isfinite([f.get(k,0) for k in ("offset","spring","viscous","coulomb")]).all():
            raise ValueError("non-finite friction")
        lines.append("  {"+",".join(values)+"},")
    lines.append("};")
    Path(out).write_text("\n".join(lines)+"\n")
    print(f"{name}: {source_hash} -> {out}")


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--urdf",required=True,type=Path)
    parser.add_argument("--friction",type=Path,help="defaults to the adjacent <urdf stem>_friction.yaml when present")
    parser.add_argument("--out",required=True)
    parser.add_argument("--name",help="LCD model name; defaults to URDF stem")
    args=parser.parse_args()
    companion=args.urdf.with_name(args.urdf.stem+"_friction.yaml")
    friction=args.friction or (companion if companion.is_file() else None)
    export(args.urdf,friction,args.out,args.name or args.urdf.stem)
