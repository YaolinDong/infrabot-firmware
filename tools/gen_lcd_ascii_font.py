"""Convert the printable ASCII glyphs of the packaged Terminus Font PSFs to LCD columns."""
import argparse
import gzip
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
FONTS = [(8, 16, "Lat2-Terminus16.psf.gz"), (12, 24, "Lat2-Terminus24x12.psf.gz")]


def read_psf(path, expected_width, expected_height):
    data = gzip.decompress(path.read_bytes())
    if data.startswith(b"\x36\x04"):
        mode, height = data[2:4]
        if not mode & 6:
            raise ValueError(f"{path}: PSF1 requires a Unicode table")
        width, count, offset, size = 8, 512 if mode & 1 else 256, 4, height
        positions = data[offset + count * size:]
        entries = positions.decode("utf-16-le").split("\uffff")
        aliases = [entry.partition("\ufffe")[0] for entry in entries]
    elif data.startswith(b"\x72\xb5\x4a\x86"):
        _, version, offset, flags, count, size, height, width = struct.unpack_from("<8I", data)
        if version != 0 or not flags & 1:
            raise ValueError(f"{path}: expected a Unicode-mapped PSF2")
        entries = data[offset + count * size:].split(b"\xff")
        aliases = [entry.partition(b"\xfe")[0].decode("utf-8") for entry in entries]
    else:
        raise ValueError(f"{path}: unknown PSF header")

    stride = (width + 7) // 8
    if (width, height) != (expected_width, expected_height) or size != stride * height:
        raise ValueError(f"{path}: incorrect glyph dimensions")
    if len(aliases) != count + 1 or aliases[-1]:
        raise ValueError(f"{path}: invalid Unicode table")
    glyphs = {}
    for index, chars in enumerate(aliases[:-1]):
        start = offset + index * size
        for char in set(chars):
            if ' ' <= char <= '~':
                if char in glyphs:
                    raise ValueError(f"{path}: ambiguous mapping for {char!r}")
                glyphs[char] = data[start:start + size]
    if set(glyphs) != set(map(chr, range(32, 127))):
        raise ValueError(f"{path}: incomplete printable ASCII mapping")
    return glyphs


def lcd_columns(rows, width, height):
    stride = (width + 7) // 8
    packed = bytearray(width * ((height + 7) // 8))
    for x in range(width):
        for y in range(height):
            if rows[y * stride + x // 8] & (0x80 >> (x % 8)):
                packed[x * ((height + 7) // 8) + y // 8] |= 0x80 >> (y % 8)
    return packed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", type=Path, default=Path("/usr/share/consolefonts"))
    parser.add_argument("--output", type=Path, default=ROOT / "ui/app_lcd_font.c")
    parser.add_argument("--check", action="store_true", help="compare with the generated file")
    args = parser.parse_args()
    lines = [
        '/* SPDX-License-Identifier: OFL-1.1',
        ' * ASCII bitmaps derived from Terminus Font, Copyright (c) 2010 Dimitar Toshkov Zhekov.',
        ' * Reserved Font Name "Terminus Font". See LICENSES/OFL-1.1-Terminus.txt.',
        ' * Generated by tools/gen_lcd_ascii_font.py, LCD columns, MSB first. */',
        '#include "app_lcd_font.h"',
    ]
    for width, height, name in FONTS:
        glyphs = read_psf(args.font_dir / name, width, height)
        lines += ['', f'/* {name}, U+0020 through U+007E. */',
                  f'const uint8_t app_lcd_font{height}[95][{width * ((height + 7) // 8)}] = {{']
        for code in range(32, 127):
            packed = lcd_columns(glyphs[chr(code)], width, height)
            values = ','.join(f'0x{byte:02x}' for byte in packed)
            lines.append(f'  {{{values}}}, /* U+{code:04X} */')
        lines.append('};')
    content = ('\n'.join(lines) + '\n').encode('ascii')
    if args.check:
        if args.output.read_bytes() != content:
            raise SystemExit(f"{args.output}: generated glyphs differ")
    else:
        args.output.write_bytes(content)


if __name__ == '__main__':
    main()
