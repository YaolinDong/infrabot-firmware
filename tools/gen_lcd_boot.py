"""Generate native-size 4-bit coverage masks. Requires Pillow and Noto CJK fonts.
Run: /usr/bin/python3 tools/gen_lcd_boot.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageFilter
ROOT = Path(__file__).resolve().parents[1]
FONT = '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
BOLD = str(ROOT/'tools/fonts/Nunito.ttf')  # SIL OFL; license alongside font
lines = ['作者：董耀琳  邮箱：dong1505lin@gmail.com',
         'Author: Dong Yaolin  Email: dong1505lin@gmail.com']
out = ['/* SPDX-License-Identifier: OFL-1.1 */',
       '/* Generated by tools/gen_lcd_boot.py; 4-bit coverage, high nibble first. Lettering from\n * Nunito and Noto Sans CJK SC, see LICENSES/OFL-1.1-Nunito.txt and LICENSES/OFL-1.1-Noto.txt. */']
for suffix, logo_size, footer_size in [('small', 66, 14), ('large', 110, 22)]:
    for kind in ['logo', 'footer']:
        texts = ['infrabot'] if kind == 'logo' else lines
        font = ImageFont.truetype(BOLD if kind == 'logo' else FONT,
                                  logo_size if kind == 'logo' else footer_size)
        if kind == 'logo': font.set_variation_by_axes([900])
        boxes = [font.getbbox(t) for t in texts]
        width = max(b[2]-b[0] for b in boxes)+4
        height = max(b[3]-b[1] for b in boxes)+6
        im = Image.new('L', (width, height*len(texts)))
        d = ImageDraw.Draw(im)
        for i,(t,b) in enumerate(zip(texts,boxes)):
            d.text(((width-(b[2]-b[0]))//2-b[0], i*height+3-b[1]), t,font=font,fill=255)
        if kind == 'logo':
            target = 304 if suffix == 'small' else 503
            im = im.resize((target, round(im.height*target/im.width)), Image.Resampling.LANCZOS)
        vals = [(v+8)//17 for v in im.getdata()]
        if len(vals)%2: vals.append(0)
        data = [(vals[i]<<4)|vals[i+1] for i in range(0,len(vals),2)]
        name=f'boot_{kind}_{suffix}'
        out.append(f'static const uint8_t {name}_data[] = {{')
        out.extend('  '+','.join(f'0x{v:02x}' for v in data[i:i+24])+',' for i in range(0,len(data),24))
        out.append('};')
        bevel_name = '0'
        if kind == 'logo':
            # Inset face mask for the rounded shoulder of the extrusion.
            inset = im.filter(ImageFilter.MinFilter(5))
            vals = [(v+8)//17 for v in inset.getdata()]
            if len(vals)%2: vals.append(0)
            data = [(vals[i]<<4)|vals[i+1] for i in range(0,len(vals),2)]
            bevel_name = name+'_bevel'
            out.append(f'static const uint8_t {bevel_name}[] = {{')
            out.extend('  '+','.join(f'0x{v:02x}' for v in data[i:i+24])+',' for i in range(0,len(data),24))
            out.append('};')
        out.append(f'static const BootMask {name} = {{{im.width}, {im.height}, {name}_data, {bevel_name}}};')
(ROOT/'ui/app_lcd_boot_assets.inc').write_text('\n'.join(out)+'\n')
