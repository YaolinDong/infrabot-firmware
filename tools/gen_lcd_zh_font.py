"""Generate the 16x16 Chinese glyphs of the 4.3in LCD UI.

Only the characters of the Chinese strings in ui/app_lcd_ui_zh.inc are
emitted, sorted by code point (binary search on the MCU).  Each glyph is a
16x16 coverage mask, 4 bits per pixel (0 background .. 15 text), two pixels
per byte, left pixel in the high nibble, rows top to bottom (128 bytes).

Also checks that every TR("...") literal of app_lcd_ui_small.inc, and every
string the 4.3in UI shows from other modules (EXTERNAL below), has an entry
in the table, so a new English string cannot ship untranslated.

Requires Pillow and Noto Sans CJK (the same font as tools/gen_lcd_boot.py).
Run: /usr/bin/python3 tools/gen_lcd_zh_font.py
"""
import argparse
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FONT = '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
INDEX = 2   # Simplified Chinese face of the collection
SIZE, CELL, DY = 16, 16, -5   # -5: every used character keeps all its strokes in 16 rows
TABLE = ROOT / 'ui/app_lcd_ui_zh.inc'
LAYOUT = ROOT / 'ui/app_lcd_ui_small.inc'
OUTPUT = ROOT / 'ui/app_lcd_zh_font.inc'
STRING = r'"((?:[^"\\]|\\.)*)"'
# Functions of other modules whose strings the 4.3in UI shows (via SmallUi_Tr).
EXTERNAL = [
    ('control/app_local_control.c', 'AppLocalControl_Message'),
    ('control/app_gravity.c', 'AppGravity_CheckName'),
    ('app/app_tasks.c', 'AppTasks_MotorStateName'),
    ('ui/app_lcd_ui.c', 'AppLcdUi_StopReasonName'),
    ('ui/app_lcd_ui.c', 'ComplianceState'),
    ('ui/app_lcd_ui.c', 'AppLcdUi_NetSave'),
    ('ui/app_lcd_ui.c', 'AppLcdUi_NetAction'),
    ('ui/app_lcd_ui_small.inc', 'SmallUi_StateName'),
    ('ui/app_lcd_ui_small.inc', 'SmallUi_HealthName'),
]
# Shown as they are: format-only strings, numbers, abbreviations.
UNTRANSLATED = {'', '?', '%s', 'CAN', 'Saved. Now %s', '%s is not a valid a.b.c.d address'}


def function_strings(path, name):
    text = (ROOT / path).read_text(encoding='utf-8')
    m = re.search(r'\b' + name + r'\s*\([^;{]*\)\s*\{', text)
    if not m:
        sys.exit(f'{path}: {name} not found')
    body = text[m.end():text.index('\n}', m.end())]
    return set(re.findall(STRING, body))


def table_pairs(text):
    return re.findall(r'\{\s*' + STRING + r'\s*,\s*' + STRING + r'\s*\}', text)


def glyph(font, ch):
    from PIL import Image, ImageDraw
    im = Image.new('L', (CELL, CELL))
    ImageDraw.Draw(im).text(((CELL - font.getlength(ch)) / 2, DY), ch, font=font, fill=255)
    levels = [min(15, (v * 15 + 127) // 255) for v in im.getdata()]
    return bytes((levels[i] << 4) | levels[i + 1] for i in range(0, len(levels), 2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify translations without regenerating bitmaps")
    args = parser.parse_args()
    table = TABLE.read_text(encoding='utf-8')
    pairs = table_pairs(table)
    keys = [en for en, _ in pairs]
    duplicates = sorted({k for k in keys if keys.count(k) > 1})
    if duplicates:
        sys.exit(f'duplicate English keys: {duplicates}')
    used = set(re.findall(r'\bTR\(' + STRING + r'\)', LAYOUT.read_text(encoding='utf-8')))
    for path, name in EXTERNAL:
        used |= function_strings(path, name) - UNTRANSLATED
    used |= {f'{field} is not a valid a.b.c.d address' for field in ('IP', 'MASK', 'GATEWAY')}
    missing = sorted(used - set(keys))
    if missing:
        sys.exit('TR() strings without a translation:\n  ' + '\n  '.join(missing))
    names = re.search(r'small_language_names\[[^]]*\]\s*=\s*\{([^}]*)\}', table).group(1)
    zh_text = ''.join(zh for _, zh in pairs) + ''.join(re.findall(STRING, names))
    chars = sorted({c for c in zh_text if ord(c) >= 0x80})
    if any(ord(c) > 0xFFFF for c in chars):
        sys.exit('characters outside the BMP are not supported')
    if args.check:
        print(f"{len(used)} UI strings covered, {len(chars)} Chinese glyphs")
        return
    from PIL import ImageFont
    font = ImageFont.truetype(FONT, SIZE, index=INDEX)
    out = [
        '/* SPDX-License-Identifier: OFL-1.1 */',
        '/* Generated by tools/gen_lcd_zh_font.py from the strings of app_lcd_ui_zh.inc.',
        ' * Noto Sans CJK SC (SIL Open Font License), 16x16, 4-bit coverage, left pixel',
        ' * in the high nibble, rows top to bottom.  Sorted by code point.  Do not edit. */',
        f'#define APP_LCD_ZH_GLYPHS {len(chars)}U',
        'static const uint16_t app_lcd_zh_codes[APP_LCD_ZH_GLYPHS] = {',
    ]
    for i in range(0, len(chars), 12):
        out.append('  ' + ','.join(f'0x{ord(c):04X}' for c in chars[i:i + 12]) + ',')
    out.append('};')
    out.append('static const uint8_t app_lcd_zh_glyphs[APP_LCD_ZH_GLYPHS][128] = {')
    for c in chars:
        data = glyph(font, c)
        out.append(f'  {{ /* U+{ord(c):04X} {c} */')
        for i in range(0, 128, 32):
            out.append('    ' + ','.join(f'0x{b:02x}' for b in data[i:i + 32]) + ',')
        out.append('  },')
    out.append('};')
    OUTPUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{len(pairs)} strings, {len(chars)} glyphs, {len(chars) * 130} bytes -> {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
